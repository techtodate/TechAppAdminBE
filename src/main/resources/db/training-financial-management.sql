/* ============================================================
   TRAINING PAYMENT / REFUND / COMMISSION / SETTLEMENT MODULE
   V1
   ============================================================ */


/* ============================================================
   1. PAYMENT PROVIDERS
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.payment_providers
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


/* ============================================================
   2. TRAINING PAYMENT ORDERS
   One enrollment can have one or more payment attempts.
   The order represents the payment request.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_payment_orders
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    trainee_user_id BIGINT NOT NULL,
    trainer_user_id BIGINT NOT NULL,

    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    payment_provider_id BIGINT
        REFERENCES public.payment_providers(id),

    provider_order_id VARCHAR(200),

    status VARCHAR(30) NOT NULL DEFAULT 'CREATED',

    expires_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_payment_order_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_training_payment_order_status
        CHECK (
            status IN (
                'CREATED',
                'ATTEMPTED',
                'PAID',
                'FAILED',
                'EXPIRED',
                'CANCELLED'
            )
        ),

    CONSTRAINT uq_training_payment_provider_order
        UNIQUE(provider_order_id)
);

CREATE INDEX IF NOT EXISTS ix_training_payment_orders_enrollment
ON public.training_payment_orders(enrollment_id);

CREATE INDEX IF NOT EXISTS ix_training_payment_orders_trainee
ON public.training_payment_orders(trainee_user_id);


/* ============================================================
   3. TRAINING PAYMENTS
   Actual successful/failed payment transaction.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_payments
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    payment_order_id BIGINT NOT NULL
        REFERENCES public.training_payment_orders(id),

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    trainee_user_id BIGINT NOT NULL,
    trainer_user_id BIGINT NOT NULL,

    payment_provider_id BIGINT
        REFERENCES public.payment_providers(id),

    provider_payment_id VARCHAR(200),
    provider_order_id VARCHAR(200),

    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    payment_method VARCHAR(50),

    status VARCHAR(30) NOT NULL,

    captured_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_payment_amount
        CHECK (amount >= 0),

    CONSTRAINT chk_training_payment_status
        CHECK (
            status IN (
                'CREATED',
                'AUTHORIZED',
                'CAPTURED',
                'FAILED',
                'CANCELLED',
                'REFUNDED',
                'PARTIALLY_REFUNDED'
            )
        ),

    CONSTRAINT uq_training_payment_provider_payment
        UNIQUE(provider_payment_id)
);

CREATE INDEX IF NOT EXISTS ix_training_payments_enrollment
ON public.training_payments(enrollment_id);

CREATE INDEX IF NOT EXISTS ix_training_payments_status
ON public.training_payments(status);


/* ============================================================
   4. REFUND POLICY MASTER
   Business rules for cancellation/refund.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.refund_policy_rules
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(1000),

    refund_percentage NUMERIC(5,2) NOT NULL,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    display_order INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_refund_percentage
        CHECK (
            refund_percentage >= 0
            AND refund_percentage <= 100
        )
);


/* ============================================================
   5. TRAINING CANCELLATION POLICIES
   Which refund rule applies to a training offering.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_cancellation_policies
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    training_offering_id BIGINT NOT NULL
        REFERENCES public.training_offerings(id),

    before_training_start_policy_id BIGINT NOT NULL
        REFERENCES public.refund_policy_rules(id),

    between_sessions_policy_id BIGINT
        REFERENCES public.refund_policy_rules(id),

    after_training_completion_policy_id BIGINT
        REFERENCES public.refund_policy_rules(id),

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_training_cancellation_policy
        UNIQUE(training_offering_id)
);


/* ============================================================
   6. TRAINING CANCELLATIONS
   Immutable business record of cancellation request/decision.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_cancellations
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    requested_by_user_id BIGINT NOT NULL,

    cancellation_stage VARCHAR(40) NOT NULL,

    policy_rule_id BIGINT
        REFERENCES public.refund_policy_rules(id),

    refund_percentage NUMERIC(5,2),

    payment_amount NUMERIC(12,2),

    expected_refund_amount NUMERIC(12,2),

    reason VARCHAR(500),

    status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',

    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMP,
    rejected_at TIMESTAMP,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_cancellation_stage
        CHECK (
            cancellation_stage IN (
                'BEFORE_START',
                'BETWEEN_SESSIONS',
                'AFTER_COMPLETION'
            )
        ),

    CONSTRAINT chk_training_cancellation_status
        CHECK (
            status IN (
                'REQUESTED',
                'APPROVED',
                'REJECTED',
                'PROCESSED'
            )
        ),

    CONSTRAINT chk_training_cancellation_percentage
        CHECK (
            refund_percentage IS NULL
            OR (
                refund_percentage >= 0
                AND refund_percentage <= 100
            )
        )
);

CREATE INDEX IF NOT EXISTS ix_training_cancellations_enrollment
ON public.training_cancellations(enrollment_id);


/* ============================================================
   7. TRAINING REFUNDS
   Actual refund transaction sent to payment provider.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_refunds
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    cancellation_id BIGINT NOT NULL
        REFERENCES public.training_cancellations(id),

    payment_id BIGINT NOT NULL
        REFERENCES public.training_payments(id),

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    payment_provider_id BIGINT
        REFERENCES public.payment_providers(id),

    refund_amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    provider_refund_id VARCHAR(200),

    status VARCHAR(30) NOT NULL DEFAULT 'CREATED',

    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP,

    failure_reason VARCHAR(1000),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_refund_amount
        CHECK (refund_amount > 0),

    CONSTRAINT chk_training_refund_status
        CHECK (
            status IN (
                'CREATED',
                'PROCESSING',
                'PROCESSED',
                'FAILED',
                'CANCELLED'
            )
        ),

    CONSTRAINT uq_training_refund_provider
        UNIQUE(provider_refund_id)
);

CREATE INDEX IF NOT EXISTS ix_training_refunds_enrollment
ON public.training_refunds(enrollment_id);


/* ============================================================
   8. PLATFORM COMMISSION RULES
   Master configuration.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.platform_commission_rules
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,

    description VARCHAR(1000),

    commission_type VARCHAR(30) NOT NULL,

    percentage NUMERIC(7,4),
    fixed_amount NUMERIC(12,2),

    currency VARCHAR(10) DEFAULT 'INR',

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_commission_type
        CHECK (
            commission_type IN (
                'PERCENTAGE',
                'FIXED',
                'PERCENTAGE_PLUS_FIXED'
            )
        ),

    CONSTRAINT chk_commission_percentage
        CHECK (
            percentage IS NULL
            OR (
                percentage >= 0
                AND percentage <= 100
            )
        ),

    CONSTRAINT chk_commission_fixed
        CHECK (
            fixed_amount IS NULL
            OR fixed_amount >= 0
        )
);


/* ============================================================
   9. COMMISSION RULE VERSIONS
   Keeps historical commission rates intact.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.platform_commission_rule_versions
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    commission_rule_id BIGINT NOT NULL
        REFERENCES public.platform_commission_rules(id),

    version_number INTEGER NOT NULL,

    percentage NUMERIC(7,4),
    fixed_amount NUMERIC(12,2),

    effective_from TIMESTAMP NOT NULL,
    effective_to TIMESTAMP,

    active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_commission_rule_version
        UNIQUE(commission_rule_id, version_number)
);


/* ============================================================
   10. TRAINING COMMISSIONS
   Snapshot of commission actually applied to enrollment.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_commissions
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    payment_id BIGINT NOT NULL
        REFERENCES public.training_payments(id),

    commission_rule_id BIGINT
        REFERENCES public.platform_commission_rules(id),

    commission_rule_version_id BIGINT
        REFERENCES public.platform_commission_rule_versions(id),

    gross_amount NUMERIC(12,2) NOT NULL,

    commission_percentage NUMERIC(7,4),
    commission_fixed_amount NUMERIC(12,2) DEFAULT 0,

    commission_amount NUMERIC(12,2) NOT NULL,

    trainer_amount NUMERIC(12,2) NOT NULL,

    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    calculated_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_commission_status
        CHECK (
            status IN (
                'PENDING',
                'CALCULATED',
                'SETTLED',
                'CANCELLED'
            )
        ),

    CONSTRAINT chk_training_commission_amounts
        CHECK (
            gross_amount >= 0
            AND commission_amount >= 0
            AND trainer_amount >= 0
        )
);

CREATE INDEX IF NOT EXISTS ix_training_commissions_enrollment
ON public.training_commissions(enrollment_id);


/* ============================================================
   12. TRAINING SETTLEMENTS
   Settlement batch / transaction for trainer.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_settlements
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    trainer_user_id BIGINT NOT NULL,

    payment_account_id BIGINT
        REFERENCES public.trainer_payout_accounts(id),

    amount NUMERIC(12,2) NOT NULL,
    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    payment_provider_id BIGINT
        REFERENCES public.payment_providers(id),

    provider_transfer_id VARCHAR(200),

    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    eligible_at TIMESTAMP,
    initiated_at TIMESTAMP,
    completed_at TIMESTAMP,

    failure_reason VARCHAR(1000),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_settlement_amount
        CHECK (amount > 0),

    CONSTRAINT chk_training_settlement_status
        CHECK (
            status IN (
                'PENDING',
                'ELIGIBLE',
                'PROCESSING',
                'COMPLETED',
                'FAILED',
                'REVERSED',
                'CANCELLED'
            )
        ),

    CONSTRAINT uq_training_settlement_provider_transfer
        UNIQUE(provider_transfer_id)
);


/* ============================================================
   13. TRAINING SETTLEMENT ITEMS
   Links settlement to individual enrollments/commissions.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.training_settlement_items
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    settlement_id BIGINT NOT NULL
        REFERENCES public.training_settlements(id),

    commission_id BIGINT NOT NULL
        REFERENCES public.training_commissions(id),

    enrollment_id INTEGER NOT NULL
        REFERENCES public.training_enrollments(id),

    amount NUMERIC(12,2) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_training_settlement_item_amount
        CHECK (amount > 0),

    CONSTRAINT uq_training_settlement_commission
        UNIQUE(settlement_id, commission_id)
);


/* ============================================================
   14. PAYMENT WEBHOOK EVENTS
   Idempotent Razorpay webhook processing.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.payment_webhook_events
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    payment_provider_id BIGINT
        REFERENCES public.payment_providers(id),

    provider_event_id VARCHAR(200) NOT NULL,

    event_type VARCHAR(150) NOT NULL,

    payload TEXT,

    processing_status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',

    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP,

    failure_reason VARCHAR(1000),

    CONSTRAINT uq_payment_webhook_event
        UNIQUE(provider_event_id),

    CONSTRAINT chk_payment_webhook_status
        CHECK (
            processing_status IN (
                'RECEIVED',
                'PROCESSING',
                'PROCESSED',
                'FAILED',
                'IGNORED'
            )
        )
);


/* ============================================================
   15. PAYMENT TRANSACTION LEDGER
   Application-level financial audit trail.
   ============================================================ */

CREATE TABLE IF NOT EXISTS public.payment_transactions_ledger
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    enrollment_id INTEGER
        REFERENCES public.training_enrollments(id),

    payment_id BIGINT
        REFERENCES public.training_payments(id),

    refund_id BIGINT
        REFERENCES public.training_refunds(id),

    commission_id BIGINT
        REFERENCES public.training_commissions(id),

    settlement_id BIGINT
        REFERENCES public.training_settlements(id),

    transaction_type VARCHAR(50) NOT NULL,

    amount NUMERIC(12,2) NOT NULL,

    currency VARCHAR(10) NOT NULL DEFAULT 'INR',

    reference_id VARCHAR(200),

    description VARCHAR(1000),

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_payment_ledger_type
        CHECK (
            transaction_type IN (
                'PAYMENT',
                'REFUND',
                'COMMISSION',
                'TRAINER_PAYABLE',
                'TRAINER_SETTLEMENT',
                'SETTLEMENT_REVERSAL'
            )
        )
);

CREATE INDEX IF NOT EXISTS ix_payment_ledger_enrollment
ON public.payment_transactions_ledger(enrollment_id);

CREATE INDEX IF NOT EXISTS ix_payment_ledger_type
ON public.payment_transactions_ledger(transaction_type);

/* Administrative mutations are recorded separately from the immutable ledger. */
CREATE TABLE IF NOT EXISTS public.training_financial_admin_audit
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_username VARCHAR(200) NOT NULL,
    action VARCHAR(100) NOT NULL,
    target_type VARCHAR(100) NOT NULL,
    target_id BIGINT NOT NULL,
    result VARCHAR(30) NOT NULL,
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_training_financial_admin_audit_target
ON public.training_financial_admin_audit(target_type, target_id, created_at);



