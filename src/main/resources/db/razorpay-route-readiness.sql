-- Razorpay Route Test Mode mappings and explicit transfer-test audit.
-- Safe to run more than once. Does not alter existing payout/account records.
BEGIN;

CREATE TABLE IF NOT EXISTS public.razorpay_route_linked_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_user_id BIGINT NOT NULL,
    payout_account_id BIGINT NOT NULL REFERENCES public.trainer_payout_accounts(id),
    provider VARCHAR(30) NOT NULL DEFAULT 'RAZORPAY',
    provider_environment VARCHAR(10) NOT NULL,
    route_account_id VARCHAR(200) NOT NULL,
    account_status VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN',
    activation_status VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN',
    settlement_verification_status VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN',
    last_synced_at TIMESTAMP,
    last_error_code VARCHAR(100),
    created_by_admin_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_route_account_environment CHECK (provider_environment IN ('TEST','LIVE')),
    CONSTRAINT uq_route_account_env UNIQUE(provider_environment,route_account_id),
    CONSTRAINT uq_route_trainer_payout_env UNIQUE(provider_environment,trainer_user_id,payout_account_id)
);

ALTER TABLE public.razorpay_route_linked_accounts
    ADD COLUMN IF NOT EXISTS settlement_verification_status VARCHAR(40) NOT NULL DEFAULT 'UNKNOWN';

CREATE TABLE IF NOT EXISTS public.razorpay_route_test_transfer_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_environment VARCHAR(10) NOT NULL,
    payment_provider_payment_id VARCHAR(200) NOT NULL,
    route_linked_account_id BIGINT NOT NULL REFERENCES public.razorpay_route_linked_accounts(id),
    amount_paise BIGINT NOT NULL CHECK (amount_paise > 0),
    provider_transfer_id VARCHAR(200),
    attempt_status VARCHAR(30) NOT NULL,
    provider_http_status INTEGER,
    provider_error_code VARCHAR(100),
    reconciliation_status VARCHAR(30) NOT NULL DEFAULT 'UNKNOWN',
    initiated_by_admin_id BIGINT,
    request_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    response_timestamp TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_route_transfer_environment CHECK (provider_environment IN ('TEST','LIVE')),
    CONSTRAINT ck_route_transfer_attempt_status CHECK (attempt_status IN ('PROCESSING','SUCCESS','FAILED','UNKNOWN'))
);

CREATE TABLE IF NOT EXISTS public.razorpay_route_onboarding_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_environment VARCHAR(10) NOT NULL,
    trainer_user_id BIGINT NOT NULL,
    payout_account_id BIGINT NOT NULL REFERENCES public.trainer_payout_accounts(id),
    reference_id VARCHAR(200) NOT NULL UNIQUE,
    attempt_status VARCHAR(30) NOT NULL,
    provider_http_status INTEGER,
    provider_error_code VARCHAR(100),
    route_account_id VARCHAR(200),
    initiated_by_admin_id BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_route_onboarding_environment CHECK (provider_environment IN ('TEST','LIVE')),
    CONSTRAINT ck_route_onboarding_status CHECK (attempt_status IN ('PROCESSING','SUCCESS','FAILED','UNKNOWN'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_route_onboarding_active_mapping
    ON public.razorpay_route_onboarding_attempts(provider_environment,trainer_user_id,payout_account_id)
    WHERE attempt_status IN ('PROCESSING','UNKNOWN','SUCCESS');

CREATE UNIQUE INDEX IF NOT EXISTS uq_route_test_transfer_active_payment
    ON public.razorpay_route_test_transfer_attempts(provider_environment,payment_provider_payment_id)
    WHERE attempt_status IN ('PROCESSING','UNKNOWN','SUCCESS');

INSERT INTO public.admin_permissions(code,name,module,description,is_active) VALUES
 ('TRAINING_FINANCIAL_VIEW','TRAINING_FINANCIAL_VIEW','FINANCE','View training financial data.',TRUE),
 ('TRAINING_FINANCIAL_MANAGE','TRAINING_FINANCIAL_MANAGE','FINANCE','Manage training financial configuration.',TRUE),
 ('TRAINING_SETTLEMENT_PROCESS','TRAINING_SETTLEMENT_PROCESS','FINANCE','Process training settlements.',TRUE)
ON CONFLICT (code) DO NOTHING;

INSERT INTO public.admin_role_permission_mapping(admin_role_id,admin_permission_id)
SELECT r.id,p.id FROM public.admin_roles r CROSS JOIN public.admin_permissions p
WHERE r.code='SUPER_ADMIN' AND p.code IN ('TRAINING_FINANCIAL_VIEW','TRAINING_FINANCIAL_MANAGE','TRAINING_SETTLEMENT_PROCESS') AND p.is_active=TRUE
ON CONFLICT DO NOTHING;

COMMIT;
