/* Repoint Admin review actor references from Main App users to Admin accounts.
   Existing actor values remain legacy/unvalidated; new writes must reference
   an Admin account. */
DO $$
DECLARE
    fk RECORD;
    child_table TEXT;
BEGIN
    FOR fk IN
        SELECT c.conname, c.conrelid::regclass AS child_relation
        FROM pg_constraint c
        JOIN pg_class child ON child.oid=c.conrelid
        JOIN pg_namespace n ON n.oid=child.relnamespace
        WHERE c.contype='f' AND c.confrelid=to_regclass('public.users') AND n.nspname='public'
          AND ((child.relname='user_verification_requests' AND pg_get_constraintdef(c.oid) LIKE '%assigned_reviewer_id%')
            OR (child.relname IN ('verification_sections','verification_evidence','verification_identity') AND pg_get_constraintdef(c.oid) LIKE '%reviewed_by%')
            OR (child.relname='events' AND pg_get_constraintdef(c.oid) LIKE '%reviewed_by_user_id%')
            OR (child.relname='verification_review_history' AND pg_get_constraintdef(c.oid) LIKE '%admin_user_id%'))
    LOOP
        child_table := fk.child_relation::text;
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I',child_table,fk.conname);
        IF child_table LIKE '%verification_review_history' THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (admin_user_id) REFERENCES public.admin_users(id) ON DELETE RESTRICT NOT VALID',child_table,fk.conname);
        ELSIF child_table LIKE '%user_verification_requests' THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (assigned_reviewer_id) REFERENCES public.admin_users(id) ON DELETE SET NULL NOT VALID',child_table,fk.conname);
        ELSIF child_table LIKE '%events' THEN
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (reviewed_by_user_id) REFERENCES public.admin_users(id) ON DELETE SET NULL NOT VALID',child_table,fk.conname);
        ELSE
            EXECUTE format('ALTER TABLE %s ADD CONSTRAINT %I FOREIGN KEY (reviewed_by) REFERENCES public.admin_users(id) ON DELETE SET NULL NOT VALID',child_table,fk.conname);
        END IF;
        /* Keep old actor references as legacy rows; PostgreSQL enforces the new
           Admin-account FK for all subsequent inserts and updates. */
    END LOOP;
END $$;
