/* Admin-only identity, session and role/permission schema. */
CREATE TABLE IF NOT EXISTS public.admin_users (
    /* Keep Admin IDs away from legacy public.users IDs while remaining safe in JS JSON clients. */
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 8000000000000000) PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    must_change_password BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_admin_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS public.admin_roles (
    id BIGSERIAL PRIMARY KEY,
    code VARCHAR(60) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    system_role BOOLEAN NOT NULL DEFAULT FALSE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.admin_permissions (
    id BIGSERIAL PRIMARY KEY,
    code VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.admin_user_roles (
    admin_user_id BIGINT NOT NULL REFERENCES public.admin_users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES public.admin_roles(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (admin_user_id, role_id)
);

CREATE TABLE IF NOT EXISTS public.admin_role_permissions (
    role_id BIGINT NOT NULL REFERENCES public.admin_roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES public.admin_permissions(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS public.admin_sessions (
    id BIGSERIAL PRIMARY KEY,
    admin_user_id BIGINT NOT NULL REFERENCES public.admin_users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_used_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_agent VARCHAR(500),
    remote_address VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS public.admin_login_attempts (
    email VARCHAR(320) PRIMARY KEY,
    failed_attempts INTEGER NOT NULL DEFAULT 0,
    locked_until TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_admin_sessions_user_active ON public.admin_sessions(admin_user_id, expires_at) WHERE revoked_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_admin_user_roles_role ON public.admin_user_roles(role_id);
CREATE INDEX IF NOT EXISTS idx_admin_role_permissions_permission ON public.admin_role_permissions(permission_id);

